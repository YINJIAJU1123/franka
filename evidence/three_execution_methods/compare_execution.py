@contextlib.contextmanager
def no_ip_sockets():
    original = socket.socket
    attempts = []

    def deny(family=socket.AF_INET, *args, **kwargs):
        if family in (socket.AF_INET, socket.AF_INET6):
            attempts.append(int(family))
            raise RuntimeError("IP sockets are forbidden in this offline audit")
        return original(family, *args, **kwargs)

    socket.socket = deny
    try:
        yield attempts
    finally:
        socket.socket = original


def digest(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as f:
        for b in iter(lambda: f.read(2**20), b""):
            h.update(b)
    return h.hexdigest()


def quantiles(x):
    x = np.asarray(x, dtype=float)
    return np.percentile(x, [50, 95, 100]).tolist() if len(x) else [None] * 3


def events(raw):
    state = False
    binary = []
    result = []
    for i, x in enumerate(raw):
        new = (x > 0.45) if state else (x >= 0.55)
        if new != state:
            result.append({"type": "close" if new else "open", "frame": i, "time_s": i / 30})
        state = new
        binary.append(float(state))
    return np.asarray(binary), result


def first_sustained_below(z, threshold, limit):
    mask = np.asarray(z[:limit]) <= threshold
    if len(mask) < 3:
        return None
    where = np.flatnonzero(np.convolve(mask.astype(int), np.ones(3, dtype=int), mode="valid") == 3)
    return int(where[0]) if len(where) else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    root, out = args.root.resolve(), args.out.resolve()
    assert out != root and out.name == "execution_comparison_20261112"
    out.mkdir(parents=True, exist_ok=True)
    sys.path.insert(0, str(root))
    from act_gripper_policy import load_act_gripper_policy
    from buffer_cache_utils import load_standard_buffer_cache
    from franka_gripper_control import CartesianServo
    from lerobot.policies.act.modeling_act import ACTTemporalEnsembler

    manifest = json.loads((root / "manifest.json").read_text())
    protected = json.loads((root / "protected_source_hashes.json").read_text())
    frozen = {str(root / k): v["sha256"] for k, v in manifest["files"].items()}
    hashes = {**protected, **frozen}
    assert all(digest(p) == h for p, h in hashes.items())
    assert digest(root / "checkpoint/act_policy_ema.pth") == manifest["ema_sha256"]
    cfg = json.loads((root / "runtime_config.json").read_text())
    assert cfg["dataset"]["action_offset_frames"] == 10
    selection = json.loads((root / "recorded_metadata/episode_selection.json").read_text())
    assert selection["excluded_source_episodes"] == [6] and len(selection["mapping"]) == 14
    metadata = [json.loads(x) for x in (root / "recorded_metadata/meta/episodes.jsonl").read_text().splitlines()]
    ends = np.cumsum([x["length"] for x in metadata])
    starts = np.r_[0, ends[:-1]]
    data = Path(json.loads((root / "offline_sources.json").read_text())["dataset"])
    cache = load_standard_buffer_cache(data / "buffer_cache.pt")
    states = cache["state"].float()
    actions = cache["action"].float().numpy()
    stats = torch.load(root / "checkpoint/dataset_stats.pth", map_location="cpu", weights_only=False)
    lo = torch.as_tensor(stats["observation.state"]["min"], dtype=torch.float32, device="cuda")
    hi = torch.as_tensor(stats["observation.state"]["max"], dtype=torch.float32, device="cuda")
    alo = np.asarray(stats["action"]["min"], dtype=np.float32)
    ahi = np.asarray(stats["action"]["max"], dtype=np.float32)
    cameras = ["cam_head", "cam_wrist"]
    valid = np.concatenate([np.arange(a, b - 10) for a, b in zip(starts, ends)])
    torch.set_num_threads(8)
    result = {
        "checkpoint": str(root / "checkpoint/act_policy_ema.pth"),
        "ema_sha256": manifest["ema_sha256"],
        "excluded_source_episode": 6,
        "episodes": 14,
        "frames_evaluated": len(valid),
        "fps": 30,
        "action_offset_frames": 10,
        "method": "Same recorded observations; the next observation is not generated by predicted motion.",
        "limits": [
            "Recorded-observation replay is not an autonomous rollout or a controller test.",
            "Only episodes 2 and 4 are held out; they were already used to select run02 EMA.",
            "Stationary-input stress sequences repeat saved observations; they are not a physical rollout.",
            "No images were saved during the unsuccessful 38-second real trial.",
        ],
        "primary_methods": ["first_1", "block_100", "ensemble_0.01"],
        "additional_sensitivity_methods": ["block_10", "block_20", "block_30", "block_50", "ensemble_0.001", "ensemble_0.1"],
    }
    with no_ip_sockets() as attempts:
        policy, _, _ = load_act_gripper_policy(root / "runtime_config.json", root / "checkpoint", torch.device("cuda"), "act_policy_ema.pth")
        assert policy.config.mask_gripper_state

        def batch(indices):
            return {"observation.state": states[indices].cuda().clamp(lo, hi), **{
                f"observation.images.{c}": cache[f"observation.images.{c}"][indices].float().cuda()
                for c in cameras
            }}

        raw_path = out / "raw_chunks.npy"
        cache_stat = (data / "buffer_cache.pt").stat()
        source_signature = {"sha256": manifest["ema_sha256"], "frames": int(ends[-1]), "shape": [int(ends[-1]), 100, 8],
                            "input_cache_size": cache_stat.st_size, "input_cache_mtime_ns": cache_stat.st_mtime_ns,
                            "runtime_config_sha256": digest(root / "runtime_config.json"),
                            "dataset_stats_sha256": digest(root / "checkpoint/dataset_stats.pth")}
        signature_path = out / "raw_chunks_signature.json"
        reuse = raw_path.exists() and signature_path.exists() and json.loads(signature_path.read_text()) == source_signature
        if reuse:
            chunks = np.load(raw_path, mmap_mode="r")
            print("REUSING exact checkpoint/input chunk cache", flush=True)
        else:
            chunks = np.lib.format.open_memmap(raw_path, mode="w+", dtype=np.float32, shape=tuple(source_signature["shape"]))
            chunks[:] = np.nan
            t0 = time.monotonic()
            with torch.inference_mode():
                for offset in range(0, len(valid), 64):
                    ix = valid[offset:offset + 64]
                    prediction = policy.predict_action_chunk(batch(ix))
                    assert tuple(prediction.shape) == (len(ix), 100, 8) and bool(torch.isfinite(prediction).all())
                    chunks[ix] = prediction.cpu().numpy()
                    if offset % 2048 == 0:
                        print(f"INFER {offset}/{len(valid)} elapsed={time.monotonic() - t0:.1f}s", flush=True)
            chunks.flush()
            signature_path.write_text(json.dumps(source_signature, indent=2))
            result["inference_wall_time_s"] = time.monotonic() - t0

        previous = np.load(root / "reports/first_action_predictions.npz")
        assert np.array_equal(previous["indices"], valid)
        result["max_difference_from_previous_first_action_replay"] = float(np.max(np.abs(np.clip(chunks[valid, 0], alo, ahi) - previous["predictions"])))
        assert result["max_difference_from_previous_first_action_replay"] < 5e-5

        def execute(raw, name):
            n = len(raw)
            if name == "first_1":
                a = raw[:, 0].copy()
            elif name.startswith("block_"):
                size = int(name.split("_")[1])
                t = np.arange(n)
                a = raw[t // size * size, t % size].copy()
            else:
                coefficient = float(name.split("_")[1])
                ensembler = ACTTemporalEnsembler(coefficient, 100)
                a = np.stack([ensembler.update(torch.from_numpy(np.array(x, copy=True))[None])[0].numpy().copy() for x in raw])
            return np.clip(a, alo, ahi)

        # Match inference batch sizes for selector equivalence. CUDA batch-1 and batch-64
        # kernels can differ slightly; characterize that separately from execution logic.
        with torch.inference_mode():
            single_chunks = np.stack([policy.predict_action_chunk(batch([i]))[0].cpu().numpy() for i in range(105)])
        result["batch_numerical_difference_max_rad_or_gripper"] = float(np.max(np.abs(single_chunks - chunks[:105])))
        # Check offline selectors against the actual loaded LeRobot select_action, including a block boundary.
        result["selector_equivalence"] = {}
        for name in result["primary_methods"]:
            policy.config.temporal_ensemble_coeff = 0.01 if name.startswith("ensemble_") else None
            policy.config.n_action_steps = 100 if name == "block_100" else 1
            if name.startswith("ensemble_"):
                policy.temporal_ensembler = ACTTemporalEnsembler(0.01, 100)
            policy.reset()
            got = []
            with torch.inference_mode():
                for i in range(105):
                    got.append(policy.select_action(batch([i]))[0].cpu().numpy())
            difference = float(np.max(np.abs(np.clip(got, alo, ahi) - execute(single_chunks, name))))
            result["selector_equivalence"][name] = {"frames": 105, "max_abs_difference": difference}
            assert difference < 1e-6, (name, difference)

        servo = CartesianServo(str(root / "fr3.urdf"))

        def fk(sequence):
            return np.stack([servo.fk(q[:7])[0] for q in sequence])

        result["batch_numerical_first_pose_difference_mm_max"] = float(np.linalg.norm(
            fk(np.clip(single_chunks[:, 0], alo, ahi)) - fk(np.clip(chunks[:105, 0], alo, ahi)), axis=1).max() * 1000)

        methods = result["primary_methods"] + result["additional_sensitivity_methods"]
        details = {name: [] for name in methods}
        plot_arrays = {}
        # All primary and sensitivity candidates see identical frames and use identical grip hysteresis.
        for ep, (a, b) in enumerate(zip(starts, ends)):
            a, b = int(a), int(b)
            n = b - a - 10
            raw = chunks[a:a + n]
            reference = actions[a + 10:b]
            xyz_ref = fk(reference)
            ref_bit, ref_events = events(reference[:, 7])
            expected_close = next(x["frame"] for x in ref_events if x["type"] == "close")
            close_limit = min(n, expected_close + 90)
            initial_z = xyz_ref[0, 2]
            descent = initial_z - xyz_ref[expected_close, 2]
            for name in methods:
                selected = execute(raw, name)
                xyz = fk(selected)
                bit, ev = events(selected[:, 7])
                error = xyz - xyz_ref
                event_match = [x["type"] for x in ev] == [x["type"] for x in ref_events]
                timing = [(x["frame"] - y["frame"]) / 30 for x, y in zip(ev, ref_events)] if event_match else []
                milestones = []
                for fraction in [.25, .5, .75, .9]:
                    threshold = initial_z - fraction * descent
                    rt = first_sustained_below(xyz_ref[:, 2], threshold, close_limit)
                    pt = first_sustained_below(xyz[:, 2], threshold, close_limit)
                    milestones.append({"fraction": fraction, "reference_frame": rt, "prediction_frame": pt,
                                       "timing_error_s": (pt - rt) / 30 if rt is not None and pt is not None else None})
                boundary = np.arange(int(name.split("_")[1]), n, int(name.split("_")[1])) if name.startswith("block_") else np.array([], int)
                item = {"training_episode": ep, "source_episode": selection["mapping"][ep]["source_episode"],
                        "split": "held_out" if ep in [2, 4] else "train", "frames": n,
                        "target_adjacent_step_mm_p50_p95_max": quantiles(np.linalg.norm(np.diff(xyz, axis=0), axis=1) * 1000),
                        "reference_residual_adjacent_mm_p50_p95_max": quantiles(np.linalg.norm(np.diff(error, axis=0), axis=1) * 1000),
                        "target_second_difference_mm_p50_p95_max": quantiles(np.linalg.norm(np.diff(xyz, n=2, axis=0), axis=1) * 1000),
                        "pose_error_mm_p50_p95_max": quantiles(np.linalg.norm(error, axis=1) * 1000),
                        "joint_mae_rad": float(np.abs(selected[:, :7] - reference[:, :7]).mean()),
                        "gripper_accuracy": float(np.mean(bit == ref_bit)), "expected_events": ref_events,
                        "predicted_events": ev, "event_types_match": event_match, "event_timing_errors_s": timing,
                        "all_events_within_1s": bool(event_match and len(timing) == 2 and max(abs(x) for x in timing) <= 1),
                        "expected_preclose_descent_mm": float(descent * 1000),
                        "target_descent_at_expected_close_mm": float((initial_z - xyz[expected_close, 2]) * 1000),
                        "progress_milestones": milestones,
                        "block_boundary_step_mm_p50_p95_max": quantiles(np.linalg.norm(xyz[boundary] - xyz[boundary - 1], axis=1) * 1000)}
                details[name].append(item)
                if ep in [0, 2, 4]:
                    prefix = f"ep{ep}_{name}"
                    plot_arrays[prefix + "_xyz"] = xyz.astype(np.float32)
                    plot_arrays[prefix + "_gripper"] = selected[:, 7]
                    plot_arrays[prefix + "_binary"] = bit.astype(np.float32)
            if ep in [0, 2, 4]:
                plot_arrays[f"ep{ep}_reference_xyz"] = xyz_ref.astype(np.float32)
                plot_arrays[f"ep{ep}_reference_gripper"] = ref_bit.astype(np.float32)
            print(f"METRICS episode={ep} frames={n}", flush=True)

        def aggregate(rows):
            times = [abs(t) for x in rows for t in x["event_timing_errors_s"]]
            progress = [abs(m["timing_error_s"]) for x in rows for m in x["progress_milestones"] if m["timing_error_s"] is not None]
            return {"episodes": len(rows), "target_adjacent_p95_mm_episode_median": float(np.median([x["target_adjacent_step_mm_p50_p95_max"][1] for x in rows])),
                    "residual_adjacent_p95_mm_episode_median": float(np.median([x["reference_residual_adjacent_mm_p50_p95_max"][1] for x in rows])),
                    "pose_error_median_mm_episode_median": float(np.median([x["pose_error_mm_p50_p95_max"][0] for x in rows])),
                    "joint_mae_rad_episode_mean": float(np.mean([x["joint_mae_rad"] for x in rows])),
                    "gripper_accuracy_frame_weighted": float(np.average([x["gripper_accuracy"] for x in rows], weights=[x["frames"] for x in rows])),
                    "event_types_match_episodes": sum(x["event_types_match"] for x in rows),
                    "all_events_within_1s_episodes": sum(x["all_events_within_1s"] for x in rows),
                    "event_abs_timing_error_s_p50_p95_max": quantiles(times),
                    "progress_abs_timing_error_s_p50_p95_max": quantiles(progress),
                    "missing_progress_milestones": sum(m["prediction_frame"] is None for x in rows for m in x["progress_milestones"]),
                    "block_boundary_p95_mm_episode_median": float(np.median([x["block_boundary_step_mm_p50_p95_max"][1] for x in rows])) if rows[0]["block_boundary_step_mm_p50_p95_max"][1] is not None else None}

        result["recorded_replay"] = {name: {"all14": aggregate(rows), "held_out_2": aggregate([x for x in rows if x["split"] == "held_out"]), "per_episode": rows} for name, rows in details.items()}

        saved = np.load(root / "reports/after_manual_return_readonly_predictions_20261112.npz")
        obs = {key: torch.from_numpy(saved[key]).float().cuda() for key in saved.files if key.startswith("observation.")}
        obs["observation.state"] = obs["observation.state"].clamp(lo, hi)
        with torch.inference_mode():
            saved_raw = policy.predict_action_chunk(obs).cpu().numpy()
        result["stationary_stress"] = {"source": "30 saved post-return observations; repeated to 600 virtual 30Hz ticks", "results": {}}
        origin = fk(saved["observation.state"][:1])[0]
        for case, stress in [("frozen_observation", np.repeat(saved_raw[:1], 600, axis=0)),
                             ("saved_camera_sequence_cycled", saved_raw[np.arange(600) % len(saved_raw)])]:
            result["stationary_stress"]["results"][case] = {}
            for name in methods:
                selected = execute(stress, name)
                xyz = fk(selected)
                d = np.linalg.norm(np.diff(xyz, axis=0), axis=1) * 1000
                steady = xyz[150:]
                bit, ev = events(selected[:, 7])
                result["stationary_stress"]["results"][case][name] = {
                    "steady_target_std_mm": (steady.std(axis=0) * 1000).tolist(),
                    "steady_target_span_mm": (np.ptp(steady, axis=0) * 1000).tolist(),
                    "steady_adjacent_mm_p50_p95_max": quantiles(d[150:]),
                    "max_single_target_jump_mm": float(d.max()),
                    "final_target_relative_xyz_mm": ((xyz[-1] - origin) * 1000).tolist(),
                    "gripper_events": ev,
                }
                if name in result["primary_methods"]:
                    plot_arrays[f"stress_{case}_{name}_xyz"] = ((xyz - origin) * 1000).astype(np.float32)
        result["ip_socket_attempts"] = attempts
    assert not attempts
    result["integrity"] = {"protected_original_files": len(protected), "frozen_baseline_files": len(frozen),
                           "all_existing_files_unchanged": all(digest(p) == h for p, h in hashes.items()),
                           "ros_nodes_created": 0, "motion_or_gripper_commands_sent": 0}
    assert result["integrity"]["all_existing_files_unchanged"]
    np.savez_compressed(out / "comparison_traces.npz", **plot_arrays)
    (out / "comparison_results.json").write_text(json.dumps(result, indent=2))
    print("FINAL_SUMMARY", json.dumps({k: {g: v[g] for g in ["all14", "held_out_2"]} for k, v in result["recorded_replay"].items()}), flush=True)
    print("DONE", out / "comparison_results.json", flush=True)


if __name__ == "__main__":
    main()
